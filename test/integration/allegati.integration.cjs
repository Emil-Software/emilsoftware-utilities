// Integration test del modulo Allegati su Firebird reale.
// Il modulo presuppone una tabella ALLEGATI preesistente: qui la si crea se assente.
const { test } = require('node:test');
const assert = require('node:assert/strict');

const { getContext } = require('./helpers/accessiTestContext.cjs');
const { Orm } = require('../../src/Orm');
const { AllegatiService } = require('../../src/allegati-module/Services/AllegatiService/AllegatiService');

function unavailable(ctx, t) {
  if (process.env.ACCESSI_TEST_REQUIRE_DB === '1') {
    throw new Error(`Firebird richiesto ma non disponibile: ${ctx.reason}`);
  }
  t.skip(`Firebird non disponibile: ${ctx.reason}`);
  return null;
}

async function buildService(t) {
  const ctx = await getContext();
  if (!ctx.available) {
    return unavailable(ctx, t);
  }

  const db = ctx.options.databaseOptions;
  const existing = await Orm.query(
    db,
    `SELECT RDB$RELATION_NAME FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'ALLEGATI'`,
  );

  if (existing.length === 0) {
    await Orm.execute(db, `
      CREATE TABLE ALLEGATI (
        IDXALL INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        CODICE INTEGER,
        TIPCOD VARCHAR(10),
        ORDINE VARCHAR(10),
        DESALL VARCHAR(255),
        NOMEFILE VARCHAR(255),
        DADATAVAL DATE,
        ADATAVAL DATE,
        ALLEGATO BLOB SUB_TYPE 1,
        IDXTIPOALL INTEGER,
        DATMODIF TIMESTAMP,
        DOCRIF VARCHAR(64)
      )
    `);
  }

  return { ctx, service: new AllegatiService({ databaseOptions: db }) };
}

test('allegati: upload, download, lista e delete su DB reale', async (t) => {
  const built = await buildService(t);
  if (!built) return;
  const { service } = built;

  const pdf = Buffer.from('%PDF-1.4\n% integration test\n1 0 obj<<>>endobj\n%%EOF');
  const file = {
    buffer: pdf,
    size: pdf.length,
    mimetype: 'application/pdf',
    originalname: 'integration.pdf',
  };

  const uploaded = await service.uploadFile(file, {
    codice: 1,
    tipoCodice: 'IT',
    ordine: '1',
    descrizioneAllegato: 'Integration',
    idTipoAllegato: 1,
  });
  assert.ok(uploaded.id > 0);
  assert.equal(uploaded.filename, 'integration.pdf');

  const downloaded = await service.downloadFile(uploaded.id);
  assert.equal(downloaded.filename, 'integration.pdf');
  assert.equal(Buffer.from(downloaded.contentBase64, 'base64').toString('utf8'), pdf.toString('utf8'));

  const listed = await service.listFiles({ docrif: undefined });
  assert.ok(listed.some((item) => item.id === uploaded.id));

  await service.deleteFile(uploaded.id);
  await assert.rejects(() => service.downloadFile(uploaded.id));
});

test('allegati: contenuto che non corrisponde al mimetype viene rifiutato', async (t) => {
  const built = await buildService(t);
  if (!built) return;
  const { service } = built;

  const fakePdf = {
    buffer: Buffer.from('<?php echo "not a pdf";'),
    size: 22,
    mimetype: 'application/pdf',
    originalname: 'evil.pdf',
  };

  await assert.rejects(() => service.uploadFile(fakePdf, {}));
});
